#!/usr/bin/env python3
"""Fetch the openly licensed assets listed in assets/manifest.toml, verify them, and keep the credits in step.

Usage:
  python3 scripts/fetch_assets.py            download every entry to build/assets/src/, verify each sha256
  python3 scripts/fetch_assets.py --learn    download, and write the computed sha256 of any entry whose sha256 is empty
  python3 scripts/fetch_assets.py --credits  regenerate assets/CREDITS.md from the manifest
  python3 scripts/fetch_assets.py --check    no network: manifest valid, every hash filled, CREDITS.md up to date

The manifest is the licence record. CREDITS.md is generated from it and never edited by hand. Standard library only.
"""
import argparse
import hashlib
import pathlib
import sys
import tomllib
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "assets" / "manifest.toml"
CREDITS = ROOT / "assets" / "CREDITS.md"
SRC = ROOT / "build" / "assets" / "src"

# Only licences the asset policy allows (docs/asset-policy.md). Anything else fails the check.
LICENCES = {
    "CC0-1.0": "CC0 1.0 Universal (public domain dedication)",
    "CC-BY-4.0": "Creative Commons Attribution 4.0 International",
    "OFL-1.1": "SIL Open Font License 1.1",
    "CMU-MOCAP": "CMU Graphics Lab Motion Capture Database: free to copy, modify and redistribute (see source page)",
}
REQUIRED = ("id", "kind", "url", "file", "sha256", "license", "author", "source_page")
CMU_HTTP = "http://mocap.cs.cmu.edu/"
KINDS = {"texture", "model", "character", "motion", "sound", "font"}


def load() -> list[dict]:
    data = tomllib.loads(MANIFEST.read_text(encoding="utf-8"))
    entries = data.get("asset", [])
    problems = []
    seen = set()
    for e in entries:
        name = e.get("id", "?")
        for key in REQUIRED:
            if key not in e:
                problems.append(f"{name}: missing '{key}'")
        if e.get("kind") not in KINDS:
            problems.append(f"{name}: kind must be one of {sorted(KINDS)}")
        if e.get("license") not in LICENCES:
            problems.append(f"{name}: licence '{e.get('license')}' is not allowed")
        if e.get("license") in ("CC-BY-4.0",) and not e.get("author", "").strip():
            problems.append(f"{name}: CC-BY asset without an author")
        if name in seen:
            problems.append(f"{name}: duplicate id")
        seen.add(name)
        url = str(e.get("url", ""))
        # https everywhere, except the CMU mocap host, which serves plain http only (its site, its statement).
        if not (url.startswith("https://") or url.startswith(CMU_HTTP)):
            problems.append(f"{name}: url must be https (or {CMU_HTTP}...)")
    if problems:
        sys.exit("manifest:\n  " + "\n  ".join(problems))
    return entries


def sha256_of(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fetch(entry: dict) -> pathlib.Path:
    SRC.mkdir(parents=True, exist_ok=True)
    dest = SRC / entry["file"]
    if not dest.exists():
        req = urllib.request.Request(entry["url"], headers={"User-Agent": "ludens-playground-assets"})
        with urllib.request.urlopen(req, timeout=120) as r, dest.open("wb") as f:
            while chunk := r.read(1 << 20):
                f.write(chunk)
    return dest


def credits_text(entries: list[dict]) -> str:
    lines = [
        "# Credits",
        "",
        "Generated by `scripts/fetch_assets.py --credits` from `assets/manifest.toml`. Do not edit by hand.",
        "",
        "| Asset | Kind | Author | Licence | Source |",
        "|---|---|---|---|---|",
    ]
    for e in sorted(entries, key=lambda x: x["id"]):
        lines.append(
            f"| {e['id']} | {e['kind']} | {e['author']} | {e['license']} | <{e['source_page']}> |"
        )
    lines += ["", "## Licences", ""]
    for code in sorted({e["license"] for e in entries}):
        lines.append(f"- `{code}`: {LICENCES[code]}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--learn", action="store_true", help="write computed sha256 for entries with an empty sha256")
    ap.add_argument("--credits", action="store_true", help="regenerate assets/CREDITS.md")
    ap.add_argument("--check", action="store_true", help="validate manifest and CREDITS.md, no network")
    args = ap.parse_args()

    entries = load()

    if args.check:
        bad = [e["id"] for e in entries if not e["sha256"]]
        if bad:
            print("hashes missing (run --learn):", ", ".join(bad))
            return 1
        if not CREDITS.exists() or CREDITS.read_text(encoding="utf-8") != credits_text(entries):
            print("assets/CREDITS.md is out of date (run --credits)")
            return 1
        print(f"assets: {len(entries)} entries, manifest and credits OK")
        return 0

    if args.credits:
        CREDITS.write_text(credits_text(entries), encoding="utf-8")
        print(f"wrote {CREDITS.relative_to(ROOT)}")
        return 0

    # download and verify (default) or learn hashes (--learn)
    text = MANIFEST.read_text(encoding="utf-8")
    failed = 0
    for e in entries:
        path = fetch(e)
        got = sha256_of(path)
        if not e["sha256"]:
            if not args.learn:
                print(f"FAIL {e['id']}: sha256 empty; run with --learn to record {got}")
                failed += 1
                continue
            text = _set_sha(text, e["id"], got)
            print(f"learned {e['id']} {got}")
        elif got != e["sha256"]:
            print(f"FAIL {e['id']}: sha256 {got} != manifest {e['sha256']}")
            failed += 1
            continue
        print(f"ok   {e['id']} ({path.stat().st_size} bytes)")
    if args.learn:
        MANIFEST.write_text(text, encoding="utf-8")
    return 1 if failed else 0


def _set_sha(text: str, asset_id: str, digest: str) -> str:
    """Set sha256 = "" to the digest inside the [[asset]] block whose id is asset_id."""
    blocks = text.split("[[asset]]")
    for i in range(1, len(blocks)):
        if f'id = "{asset_id}"' in blocks[i]:
            blocks[i] = blocks[i].replace('sha256 = ""', f'sha256 = "{digest}"', 1)
    return "[[asset]]".join(blocks)


if __name__ == "__main__":
    raise SystemExit(main())
